const CACHE = 'ogsk-' + VERSION;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('ogsk-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

/* Cache-first for our own files; directory URLs map to their index.html;
   offline navigations to unknown pages fall back to the hub. Cross-origin
   requests (tile servers) pass straight through. */
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    let hit = await cache.match(req, { ignoreSearch: true });
    if (!hit && url.pathname.endsWith('/')) hit = await cache.match(url.pathname + 'index.html');
    if (hit) return hit;
    try {
      const res = await fetch(req);
      // keep a copy of same-origin files we didn't precache (e.g. added later)
      if (res && res.ok && res.type === 'basic') cache.put(req, res.clone()).catch(() => {});
      return res;
    } catch (err) {
      if (req.mode === 'navigate') {
        const hub = await cache.match(new URL('index.html', self.registration.scope).href);
        if (hub) return hub;
      }
      return new Response('Offline and not cached: ' + url.pathname, { status: 503, headers: { 'Content-Type': 'text/plain' } });
    }
  })());
});

/* The hub asks "are all files cached?" to show the Offline-ready chip. */
self.addEventListener('message', (event) => {
  const msg = event.data || {};
  if (msg.type !== 'status') return;
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    let cached = 0;
    for (const u of PRECACHE) if (await cache.match(new URL(u, self.registration.scope).href)) cached++;
    const reply = { type: 'status', version: VERSION, total: PRECACHE.length, cached };
    if (event.ports && event.ports[0]) event.ports[0].postMessage(reply);
    else if (event.source) event.source.postMessage(reply);
  })());
});
