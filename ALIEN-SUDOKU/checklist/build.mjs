#!/usr/bin/env node
/* ============================================================
   Launch checklist: one source, two views.

   tasks.json     every task (phase, store, owner, steps, tips, links)
   meta.json      phases and stores
   progress.json  who checked what off, exported from the live page

   node build.mjs [--page <out.html>]
     -> rewrites the checklist part of ../README.md (green checks)
     -> writes the live page (dashboard.html) with the data built in
   ============================================================ */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f, fallback) => (existsSync(join(here, f)) ? JSON.parse(readFileSync(join(here, f), 'utf8')) : fallback);
const meta = read('meta.json');
const tasks = read('tasks.json');
const progress = read('progress.json', {});
const feedback = read('feedback.json', []);
const pageOut = process.argv.includes('--page') ? resolve(process.argv[process.argv.indexOf('--page') + 1]) : join(here, 'dashboard.html');

// ---------- checks ----------
const ids = new Set();
const problems = [];
for (const t of tasks) {
  if (ids.has(t.id)) problems.push(`duplicate id ${t.id}`);
  ids.add(t.id);
  if (!meta.phases.some((p) => p.id === t.phase)) problems.push(`${t.id}: unknown phase ${t.phase}`);
  if (!meta.stores[t.store]) problems.push(`${t.id}: unknown store ${t.store}`);
  if (!['you', 'claude', 'both'].includes(t.owner)) problems.push(`${t.id}: bad owner ${t.owner}`);
}
for (const t of tasks) for (const d of t.depends || []) if (!ids.has(d)) problems.push(`${t.id}: depends on missing ${d}`);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const isDone = (t) => (progress[t.id] ? !!progress[t.id].done : t.status === 'done');
const done = tasks.filter(isDone).length;
const pct = Math.round((done / tasks.length) * 100);

// ---------- README ----------
const mark = (t) => (isDone(t) ? '✅' : t.status === 'blocked' ? '⛔' : '⬜');
const who = { you: '👤 You', claude: '🤖 Claude', both: '👤🤖 Both' };
const esc = (s) => String(s).replace(/</g, '&lt;').replace(/\|/g, '\\|');
const bar = (n, total) => { const k = Math.round((n / total) * 20); return `${'🟩'.repeat(k)}${'⬛'.repeat(20 - k)}`; };
let md = `<!-- checklist:start (generated by checklist/build.mjs, do not edit by hand) -->\n`;
md += `## Launch checklist: ${done} of ${tasks.length} done (${pct}%)\n\n${bar(done, tasks.length)}\n\n`;
md += `✅ done · ⬜ to do · ⛔ blocked (the note says why) · 👤 you · 🤖 Claude\n\n`;
md += `| Phase | Done | Progress |\n|---|---|---|\n`;
for (const p of meta.phases) {
  const list = tasks.filter((t) => t.phase === p.id);
  if (!list.length) continue;
  const d = list.filter(isDone).length;
  md += `| ${d === list.length ? '✅ ' : ''}${p.name} | ${d} / ${list.length} | ${bar(d, list.length)} |\n`;
}
md += `\n`;
const nextUp = tasks.filter((t) => !isDone(t) && t.status !== 'blocked' && (t.depends || []).every((d) => isDone(tasks.find((x) => x.id === d)))).slice(0, 6);
if (nextUp.length) md += `### Next up\n\n${nextUp.map((t) => `- ${mark(t)} **${esc(t.title)}** · ${who[t.owner]} · ${meta.stores[t.store].name}`).join('\n')}\n\n`;
meta.phases.forEach((p, k) => {
  const list = tasks.filter((t) => t.phase === p.id);
  if (!list.length) return;
  const d = list.filter(isDone).length;
  md += `### ${k + 1}. ${p.name} (${d}/${list.length})\n\n_${p.blurb}_\n\n`;
  for (const t of list) {
    const pr = progress[t.id];
    const meta2 = [who[t.owner], meta.stores[t.store].name, t.cost, !isDone(t) && t.time].filter(Boolean).join(' · ');
    md += `<details><summary>${mark(t)} <b>${esc(t.title)}</b> · ${esc(meta2)}</summary>\n\n`;
    if (t.statusNote) md += `${t.status === 'blocked' && !isDone(t) ? '**Blocked:** ' : ''}${t.statusNote}\n\n`;
    if (t.steps?.length) md += `**Steps**\n\n${t.steps.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n`;
    if (t.feedback?.length) md += `**Tips and watch-outs**\n\n${t.feedback.map((s) => `- ${s}`).join('\n')}\n\n`;
    if (t.depends?.length) md += `**Do these first:** ${t.depends.map((d0) => { const x = tasks.find((y) => y.id === d0); return `${mark(x)} ${esc(x.title)}`; }).join(' · ')}\n\n`;
    if (t.links?.length) md += `**Links:** ${t.links.map((l) => `[${l.label}](${l.url})`).join(' · ')}\n\n`;
    if (pr?.note) md += `**Notes:** ${esc(pr.note)}\n\n`;
    if (isDone(t) && pr?.at) md += `_Checked off ${new Date(pr.at).toISOString().slice(0, 10)}${pr.by === 'claude' ? ' by Claude' : ''}._\n\n`;
    md += `</details>\n\n`;
  }
});
const open = feedback.filter((f) => f.status !== 'fixed' && f.status !== 'wontfix');
md += `## Bugs and feedback\n\n`;
md += feedback.length
  ? `${open.length} open · ${feedback.filter((f) => f.status === 'fixed').length} fixed · ${feedback.length} total (last export from the live page).\n\n${open.slice(0, 20).map((f) => `- ${f.severity === 'blocker' ? '🛑' : f.severity === 'major' ? '🟧' : '🟦'} **${esc(f.title)}** · ${esc(f.platform)} · ${esc(f.area)} · ${f.status}`).join('\n')}\n\n`
  : `No reports yet. Testers report in the **Bugs & feedback** tab of the live page; Claude exports them here.\n\n`;
md += `<!-- checklist:end -->`;

const readmePath = join(here, '..', 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const start = readme.indexOf('<!-- checklist:start');
const end = readme.indexOf('<!-- checklist:end -->');
if (start < 0 || end < 0) { console.error('README.md has no checklist markers'); process.exit(1); }
writeFileSync(readmePath, readme.slice(0, start) + md + readme.slice(end + '<!-- checklist:end -->'.length));

// ---------- live page ----------
const data = { researchedOn: meta.researchedOn, phases: meta.phases, stores: meta.stores, tasks, snapshot: progress };
const json = JSON.stringify(data).replace(/</g, '\\u003c');
const page = readFileSync(join(here, 'dashboard.template.html'), 'utf8').replace('/*__DATA__*/null', () => json);
writeFileSync(pageOut, page);
console.log(`README checklist: ${done}/${tasks.length} done (${pct}%). Page: ${pageOut} (${(page.length / 1024).toFixed(0)} KB)`);
