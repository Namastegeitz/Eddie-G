#!/usr/bin/env python3
"""Regenerate docs/DEPENDENCIES.md from what is actually installed (versions + licenses).
   python3 tools/deps_report.py"""
import json
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REASONS = {
    "react": "UI framework for the one app (spec 2.1)", "react-dom": "React DOM renderer",
    "vite": "dev server + bundler (spec 2.1)", "@vitejs/plugin-react": "React support for Vite",
    "vite-plugin-pwa": "PWA manifest + Workbox service worker for offline use (spec 2.1)",
    "@types/react": "React types", "@types/react-dom": "React DOM types", "@types/node": "Node types for tests and scripts",
    "typescript": "type-checking", "vitest": "unit + property tests (spec 14)",
    "numpy": "array math for the geometry engine", "scipy": "Bessel zeros, root finding, FFT, convolution",
    "shapely": "2D polygon ops (buffers, unions) for gobos/inserts", "trimesh": "mesh checks (watertight, winding) and STL I/O",
    "manifold3d": "guaranteed-manifold booleans and extrusion for every STL", "mapbox_earcut": "polygon triangulation used by trimesh",
    "matplotlib": "previews and contours", "contourpy": "contour extraction (nodal lines, raster gobos)",
    "pillow": "images, contact sheets, video frames", "lib3mf": "write + strictly re-read 3MF files for Bambu Studio",
    "@capacitor/core": "native bridge for the Android/iOS apps (spec 2.1, apps/mobile)",
    "@capacitor/android": "Android app shell around the web build", "@capacitor/ios": "iOS app shell around the web build",
    "@capacitor/cli": "copies the web build into the native projects (cap sync)",
}


def js_rows():
    rows = []
    for pj in [ROOT / "package.json", ROOT / "apps/web/package.json", ROOT / "apps/mobile/package.json"]:
        d = json.loads(pj.read_text())
        for sect in ("dependencies", "devDependencies"):
            for name in d.get(sect, {}):
                if name.startswith("@clc/"):
                    continue
                base = pj.parent / "node_modules" / name / "package.json"
                if not base.exists():
                    base = ROOT / "node_modules" / name / "package.json"
                m = json.loads(base.read_text())
                lic = m.get("license") or "?"
                rows.append((name, m["version"], lic if isinstance(lic, str) else lic.get("type", "?"), sect.replace("Dependencies", "").replace("dependencies", "runtime") or "runtime", str(pj.parent.relative_to(ROOT)) or "."))
    return rows


def py_rows():
    rows = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9_.-]+)==", line)
        if not m:
            continue
        name = m.group(1)
        try:
            md = metadata.metadata(name)
            lic = md.get("License-Expression") or md.get("License") or ""
            if not lic or len(lic) > 40:
                cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
                lic = ", ".join(cls) or (lic[:40] + "...")
            rows.append((name, metadata.version(name), lic))
        except metadata.PackageNotFoundError:
            rows.append((name, "not installed", "?"))
    return rows


md = ["# Dependencies", "", "Generated by `tools/deps_report.py` from the installed packages. Every new dependency must appear here with its license and the reason it was added (spec rule 2).", "",
      "## JavaScript / TypeScript (pnpm workspace)", "", "| Package | Version | License | Kind | Where | Why |", "|---|---|---|---|---|---|"]
for n, v, l, k, w in js_rows():
    md.append(f"| `{n}` | {v} | {l} | {k} | `{w}` | {REASONS.get(n, '')} |")
md += ["", "Transitive packages are pinned in `pnpm-lock.yaml`.", "", "## Python (the current STL generator and tools)", "", "| Package | Version | License | Why |", "|---|---|---|---|"]
for n, v, l in py_rows():
    md.append(f"| `{n}` | {v} | {l} | {REASONS.get(n.lower(), REASONS.get(n, ''))} |")
md += ["", "## Optional tools (not needed by CI)", "", "| Tool | License | Why |", "|---|---|---|",
       "| `bpy` 5.3 (Blender as a Python module) | GPL-3.0-or-later | Blender add-on/CLI: enhance STLs, assemble and render the chamber |",
       "| ffmpeg | LGPL-2.1+ / GPL (build-dependent) | marketing video encoding |",
       "| Playwright + Chromium | Apache-2.0 / BSD | HTML-to-PDF for the manual and sourcing guide (currently a global install in the build container) |", ""]
(ROOT / "docs/DEPENDENCIES.md").write_text("\n".join(md))
print("wrote docs/DEPENDENCIES.md")
