#!/usr/bin/env python3
"""Compute the numbers behind the build: wavelengths, dish modes, Faraday thresholds.

    python3 tools/physics_tables.py            -> docs/PHYSICS_TABLES.md

Model: linear capillary-gravity waves on water,
    omega^2 = (g k + (sigma/rho) k^3) tanh(k h)
Faraday (whole-dish) driving at f_drive makes waves at f_drive/2.
Dipper (point/shape) driving makes waves at f_drive.
Threshold (Mathieu, light damping): a_c = 4 gamma omega0 / (k tanh kh),
with bulk viscous damping gamma = 2 nu k^2 (real dishes damp 2-5x more:
walls, bottom friction at shallow depth, surface films).
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.optimize import brentq
from scipy.special import jnp_zeros

G, SIGMA, RHO, NU = 9.81, 0.072, 1000.0, 1.0e-6
ROOT = Path(__file__).resolve().parent.parent


def omega_of_k(k, h):
    return np.sqrt((G * k + SIGMA / RHO * k ** 3) * np.tanh(k * h))


def k_of_f(f, h):
    w = 2 * np.pi * f
    return brentq(lambda k: omega_of_k(k, h) - w, 1e-3, 1e6)


def wavelength_mm(f, h):
    return 2 * np.pi / k_of_f(f, h) * 1000


def faraday_threshold(f_drive, h, damping_factor=1.0):
    f = f_drive / 2
    k = k_of_f(f, h)
    w0 = 2 * np.pi * f
    gamma = 2 * NU * k * k * damping_factor
    a = 4 * gamma * w0 / (k * np.tanh(k * h))
    disp = a / (2 * np.pi * f_drive) ** 2
    return a, disp


def dish_modes(R_m, h, count=24):
    out = []
    for m in range(0, 13):
        zs = jnp_zeros(m, 4) if m > 0 else jnp_zeros(0, 4)
        for n, z in enumerate(zs, start=1):
            k = z / R_m
            f = omega_of_k(k, h) / (2 * np.pi)
            out.append((f, m, n, k))
    out.sort()
    return out[:count]


def main():
    depths = [0.002, 0.003, 0.005, 0.010]
    drives = [10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 100, 120, 150, 200]
    md = ["# Physics tables (computed)", "",
          "Generated by `tools/physics_tables.py`. Water at 20 C: surface tension 0.072 N/m, density 1000 kg/m3, "
          "kinematic viscosity 1.0e-6 m2/s. Linear theory - use it to pick starting frequencies, then tune by eye.", ""]

    md += ["## 1. Wavelength on the water (mm)", "",
           "Faraday drive (whole dish moves): the water answers at **half** the drive frequency.", "",
           "| Drive Hz | wave Hz | " + " | ".join(f"depth {d * 1000:.0f} mm" for d in depths) + " |",
           "|---|---|" + "---|" * len(depths)]
    for fd in drives:
        md.append(f"| {fd} | {fd / 2:g} | " + " | ".join(f"{wavelength_mm(fd / 2, d):.1f}" for d in depths) + " |")
    md += ["", "Dipper drive (a foot touches the surface): the water answers at the **same** frequency.", "",
           "| Drive Hz | " + " | ".join(f"depth {d * 1000:.0f} mm" for d in depths) + " |",
           "|---|" + "---|" * len(depths)]
    for fd in drives:
        md.append(f"| {fd} | " + " | ".join(f"{wavelength_mm(fd, d):.1f}" for d in depths) + " |")

    md += ["", "## 2. How hard to shake (Faraday onset, depth 5 mm)", "",
           "Peak acceleration and peak plate movement needed for patterns to appear. 'Ideal' uses bulk viscosity only; "
           "'realistic' multiplies damping by 3. Above onset, patterns sharpen; at 2-3x onset they break into chaos and droplets.", "",
           "| Drive Hz | ideal accel (g) | realistic accel (g) | realistic stroke (micrometres, peak) | force for 0.5 kg moving mass (N) |",
           "|---|---|---|---|---|"]
    for fd in drives:
        a1, _ = faraday_threshold(fd, 0.005)
        a3, d3 = faraday_threshold(fd, 0.005, 3.0)
        md.append(f"| {fd} | {a1 / G:.3f} | {a3 / G:.3f} | {d3 * 1e6:.0f} | {0.5 * a3:.2f} |")

    for name, R in [("112 mm insert cavity (R = 56 mm)", 0.056), ("145 mm dish (R = 72.5 mm)", 0.0725)]:
        md += ["", f"## 3. Natural water modes: {name}, depth 5 mm", "",
               "Free-edge circular modes J_m(k r) cos(m theta), k = j'_mn / R. To excite a mode: dipper at the "
               "listed frequency, or Faraday drive at **twice** it. m = number of nodal diameters (m-fold look), "
               "n = ring index. Previews: gobos 'Water mode J_m ring n'.", "",
               "| # | mode (m,n) | look | water Hz | Faraday drive Hz | wavelength mm |", "|---|---|---|---|---|---|"]
        for i, (f, m, n, k) in enumerate(dish_modes(R, 0.005), start=1):
            look = "rings only" if m == 0 else f"{2 * m}-petal ({m} diameters)"
            md.append(f"| {i} | ({m},{n}) | {look} | {f:.2f} | {2 * f:.2f} | {2 * np.pi / k * 1000:.1f} |")

    md += ["", "## 4. Two-frequency recipes (quasipatterns & superlattices)", "",
           "From the literature (Edwards & Fauve 1993; Kudrolli, Pier & Gollub 1998; Arbell & Fineberg 2002). "
           "Mix two sines with integer ratio m:n into the same exciter. Exact thresholds depend on fluid depth and "
           "viscosity - water is low-viscosity, so expect to work near onset and sweep slowly.", "",
           "| Ratio | Example (Hz) | What to look for |", "|---|---|---|",
           "| 4:5 | 40 + 50 | 12-fold quasipattern (Edwards & Fauve) |",
           "| 6:7 | 42 + 49 | superlattice / 12-fold, hexagon-in-hexagon (Kudrolli et al.) |",
           "| 2:3 | 40 + 60 | hexagons and triangles instead of squares |",
           "| 1:2 | 30 + 60 | hexagons favoured, phase-sensitive |",
           "| 3:5 | 36 + 60 | rhombic / mixed patterns |",
           "| 1 only | 60 | squares (low-viscosity single frequency) |"]
    out = ROOT / "docs/PHYSICS_TABLES.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
